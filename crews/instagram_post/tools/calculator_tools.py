"""
计算器工具 (Calculator Tools)
==============================
提供数学计算功能，让 AI 代理能够执行精确的数值运算。

使用场景：
- 计算营销预算分配比例
- 计算投资回报率 (ROI)
- 统计数据分析（平均值、百分比等）
- 转换不同单位（货币、时间等）
- 市场份额和增长率计算

为什么需要这个工具？
- LLM（大语言模型）在复杂计算上容易出错
- 将计算任务委托给专用工具可确保精确性
- 对于涉及财务数据的任务尤其重要
"""

from crewai import Tool
from langchain.tools import tool


class CalculatorTools:
    """
    计算工具类
    =========
    
    提供可靠的数学计算能力，弥补 LLM 在数值运算上的不足。
    """

    @tool("进行计算")
    def calculate(expression):
        """
        执行数学表达式计算
        
        支持各种数学运算类型：
        
        【基本运算】
            - 加减乘除: "1500 + 300 - 200 * 0.15"
            - 幂运算: "2 ** 10" (2的10次方)
            
        【营销相关计算】
            - ROI: "(收入 - 成本) / 成本 * 100"
            - 市场份额: "公司销售额 / 总市场规模 * 100"
            - 增长率: "(本期 - 上期) / 上期 * 100"
            - CPM/CPC: "广告费用 / 展示次数 * 1000"
            
        【统计计算】
            - 平均值: "(80 + 90 + 75 + 85) / 4"
            - 百分比占比: "3500 / 10000 * 100"
            
        参数:
            expression (str): 数学表达式字符串
            
        返回:
            str: 计算结果的字符串表示
            
        使用示例:
            >>> CalculatorTools.calculate("15000 * 0.08")
            '1200.0'
            
            >>> CalculatorTools.calculate("(5000 - 2000) / 2000 * 100")
            '150.0'  # 表示 150% 的增长
            
        安全性说明:
            - 使用 Python 内置的 eval() 执行
            - 仅用于简单的数学表达式
            - 在生产环境中建议添加安全过滤
        """
        return eval(expression)
